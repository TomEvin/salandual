namespace Salandual.App.Options;

internal sealed class HexColorsPreview : Border
{
    private static readonly byte[] _sample =
    [
        0x4D, 0x5A, 0x90, 0x00, 0x03, 0x00, 0x00, 0x00, 0x04, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0x00, 0x00,
        0xB8, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x0E, 0x1F, 0xBA, 0x0E, 0x00, 0xB4, 0x09, 0xCD, 0x21, 0xB8, 0x01, 0x4C, 0xCD, 0x21, 0x54, 0x68,
        0x69, 0x73, 0x20, 0x70, 0x72, 0x6F, 0x67, 0x72, 0x61, 0x6D, 0x20, 0x63, 0x61, 0x6E, 0x6E, 0x6F,
        0x74, 0x20, 0x62, 0x65, 0x20, 0x72, 0x75, 0x6E, 0x20, 0x69, 0x6E, 0x20, 0x44, 0x4F, 0x53, 0x20,
        0x6D, 0x6F, 0x64, 0x65, 0x2E, 0x0D, 0x0D, 0x0A, 0x24, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xE9, 0x8F, 0xC3, 0xA1, 0x7F, 0x09, 0x84, 0xF2, 0xAD, 0x50, 0x45, 0x00, 0x00, 0x64, 0x86, 0x07,
        0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    ];

    private readonly ViewerDocument _document;

    public HexColorsPreview(bool dark, ByteColors colors)
    {
        _document = new ViewerDocument("preview.bin", new MemoryByteSource(_sample));
        View = new HexContentView
        {
            Document = _document,
            ByteColors = colors,
            Focusable = false,
            IsHitTestVisible = false,
            HighlightBytes = [0x54, 0x68],
        };
        View.Select(0x2E, 0x30);
        View.SelectionIsMatch = true;
        View.Height = View.RowHeight * ((_sample.Length / 16) + 1);
        Child = new ThemeVariantScope { RequestedThemeVariant = dark ? ThemeVariant.Dark : ThemeVariant.Light, Child = View };
        this.Res(BorderBrushProperty, "Brush.Border");
        BorderThickness = new Thickness(1);
        CornerRadius = new CornerRadius(4);
        ClipToBounds = true;
        DetachedFromVisualTree += (_, _) => _document.Dispose();
    }

    internal HexContentView View { get; }
}
